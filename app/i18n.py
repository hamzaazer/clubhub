def translate_html(response, language):
    if language != "ar" or response.mimetype != "text/html":
        return response
    body = response.get_data(as_text=True)
    for source, target in sorted(ARABIC.items(), key=lambda item: len(item[0]), reverse=True):
        body = body.replace(source, target)
    response.set_data(body)
    return response
